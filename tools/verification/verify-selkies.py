spec = importlib.util.spec_from_file_location("home_lan_fixture", Path(__file__).with_name("verify-lan.py"))
lan = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lan)
lan.NAME = "ORIGINAL isolated Selkies verification"
lan.PASSWORD = "isolated-selkies-protocol-2026"


class Home(lan.Home):
    command_gate = asyncio.Lock()
    last_command = 0.0

    async def api(self, path, method="GET", payload=None, expected=200, **kwargs):
        # Both logins share an account's production command allowance. Pace
        # the rapid automation instead of weakening Home's rate limit.
        if method not in ("GET", "HEAD"):
            async with Home.command_gate:
                await asyncio.sleep(max(0, .75 - (time.monotonic() - Home.last_command)))
                Home.last_command = time.monotonic()
        return await super().api(path, method, payload, expected, **kwargs)


def docker(*args):
    return subprocess.check_output(["docker", *args], text=True).strip()


def processes(container):
    rows = docker("top", container, "-eo", "pid,comm,args").splitlines()[1:]
    return {
        "retroarch": sum("retroarch" in row.split(maxsplit=2)[1] for row in rows),
        "mediamtx": sum("mediamtx" in row.split(maxsplit=2)[1] for row in rows),
        "selkies": sum(" -m selkies " in row for row in rows),
        "sound": sum(row.split(maxsplit=2)[1] == "pulseaudio" for row in rows),
        "display": sum(row.split(maxsplit=2)[1] == "Xvfb" for row in rows),
    }


def gba_frame(container):
    code = "import socket; s=socket.socket(socket.AF_INET,socket.SOCK_DGRAM); s.settimeout(3); s.sendto(b'READ_CORE_MEMORY 2000000 12\\n',('127.0.0.1',62406)); p=s.recv(1024).decode().split(); b=bytes(int(x,16) for x in p[2:]); print(int.from_bytes(b[4:8],'little'))"
    return int(docker("exec", container, "/opt/selkies/bin/python3", "-c", code))


async def import_fixture(home, system, fixtures):
    extension = {"snes": "sfc", "megadrive": "md", "ps1": "cue"}.get(system, system)
    path = fixtures / f"ORIGINAL-ISOLATED-{system}.{extension}"
    source = path.read_bytes()
    headers = {"X-Home-Rom-Name": path.name, "X-Home-Rom-System": system}
    if system == "ps1":
        form = aiohttp.FormData()
        form.add_field("files", source, filename=path.name, content_type="application/octet-stream")
        track = fixtures / "ORIGINAL-ISOLATED-ps1.bin"
        form.add_field("files", track.read_bytes(), filename=track.name, content_type="application/octet-stream")
        result = await home.api("/api/games/roms", "POST", data=form, headers=headers)
    else:
        result = await home.api("/api/games/roms", "POST", data=source, headers=headers | {"Content-Type": "application/octet-stream"})
        assert result["sha256"] == hashlib.sha256(source).hexdigest()
    await home.api(f"/api/games/{result['id']}/preference", "PUT", {"inLibrary": True, "favorite": True})
    return result


async def connect_selkies(home, launch, ticket, pc):
    prefix = urlparse(launch["url"]).path.rstrip("/")
    # Match the released browser URL, including its trailing slash.
    socket = await home.client.ws_connect(home.base + prefix + "/api/webrtc/signaling/", origin=home.base)
    await socket.send_str("HELLO client " + json.dumps({"client_type": "viewer", "client_slot": -1,
        "client_strict_viewer": True, "client_token": ticket, "display_id": "primary", "client_tab_id": secrets.token_hex(8),
        "resume_key": secrets.token_hex(16), "fullcolor_codecs": [], "tenbit_codecs": []}))
    assert (await socket.receive(timeout=15)).data == "HELLO"
    await socket.send_str("SESSION server")

    async def pump():
        waiting = 0
        async for message in socket:
            if message.type != aiohttp.WSMsgType.TEXT:
                break
            line = message.data
            # The released browser client retries this exact startup response.
            if line == "ERROR peer server not found" and waiting < 15:
                waiting += 1
                await asyncio.sleep(1)
                await socket.send_str("SESSION server")
                continue
            assert not line.startswith("ERROR"), line
            if line.startswith("SESSION_OK"):
                continue
            peer, payload = line.split(" ", 1)
            value = json.loads(payload)
            if "sdp" in value:
                offer = value["sdp"]
                assert offer["type"] == "offer" and "H264/90000" in offer["sdp"] and "opus/48000" in offer["sdp"]
                assert any(" " + home.media_host + " 62405 " in candidate for candidate in offer["sdp"].splitlines() if candidate.startswith("a=candidate:")), offer["sdp"]
                await pc.setRemoteDescription(RTCSessionDescription(**offer))
                for tx in pc.getTransceivers():
                    kind = tx.kind
                    wanted = "video/h264" if kind == "video" else "audio/opus"
                    tx.setCodecPreferences([codec for codec in RTCRtpReceiver.getCapabilities(kind).codecs if codec.mimeType.lower() == wanted])
                await pc.setLocalDescription(await pc.createAnswer())
                await socket.send_str(peer + " " + json.dumps({"sdp": {"type": "answer", "sdp": pc.localDescription.sdp}}))
            elif "ice" in value:
                ice = value["ice"]
                if ice and ice.get("candidate"):
                    candidate = candidate_from_sdp(ice["candidate"].removeprefix("candidate:"))
                    candidate.sdpMid = ice.get("sdpMid")
                    candidate.sdpMLineIndex = ice.get("sdpMLineIndex")
                    await pc.addIceCandidate(candidate)
    return socket, asyncio.create_task(pump())


async def play(home, other, rom, system, backend, container, expected_version=None, expected_frame=None):
    ticket = secrets.token_hex(32)
    command_body = {"clientId": secrets.token_hex(16), "ticket": ticket, "streamingBackend": backend}
    launch = await home.api(f"/api/games/{rom['id']}/native-sessions", "POST", command_body)
    assert launch["streamingBackend"] == backend
    if expected_version:
        assert launch["version"] == expected_version and launch["hasSave"], launch
    if system == "gb":
        options = await home.api(f"/api/games/native/sessions/{launch['id']}/options")
        palette = next((option for option in options if option["key"] == "mgba_gb_colors"), None)
        if palette and "Grayscale" in palette["values"] and palette["value"] != "Grayscale":
            await home.api(f"/api/games/native/sessions/{launch['id']}/options", "PUT", {"key": palette["key"], "value": "Grayscale"})
    if expected_frame is not None:
        restored = None
        try:
            async with asyncio.timeout(5):
                while True:
                    restored = gba_frame(container)
                    if expected_frame <= restored <= expected_frame + 2:
                        break
                    await asyncio.sleep(.05)
        except Exception as error:
            await home.api(f"/api/games/native/sessions/{launch['id']}/command", "POST", {"action": "discard"})
            raise AssertionError(f"{backend} GBA frame restore: expected {expected_frame}, observed {restored}") from error
    retry = await home.api(f"/api/games/{rom['id']}/native-sessions", "POST", command_body)
    assert retry["id"] == launch["id"] and retry["streamingBackend"] == backend
    await home.api(f"/api/games/{rom['id']}/native-sessions", "POST", command_body | {"streamingBackend": "standard" if backend == "selkies" else "selkies"}, expected=409)
    running = processes(container)
    assert running["retroarch"] == 1 and running["mediamtx"] == (backend == "standard") and running["selkies"] == (backend == "selkies"), running
    assert running["sound"] == (backend == "selkies"), running
    pc = RTCPeerConnection(RTCConfiguration(iceServers=[]))
    receiver = {"frames": 0, "audio": 0, "nonzeroAudioFrames": 0, "rgb": None}
    tone_fixture = system in ("gba", "nes")
    consumers = []
    signal = signal_task = inputs = pulse = None
    active = True
    epoch, sequence = launch["inputEpoch"], 0

    async def command(action):
        return await home.api(f"/api/games/native/sessions/{launch['id']}/command", "POST", {"action": action})

    async def consume(track):
        try:
            while True:
                frame = await track.recv()
                if track.kind == "video":
                    rgb = frame.reformat(format="rgb24")
                    offset = rgb.height // 2 * rgb.planes[0].line_size + rgb.width // 2 * 3
                    receiver.update(frames=receiver["frames"] + 1, rgb=list(memoryview(rgb.planes[0])[offset:offset + 3]), width=frame.width, height=frame.height)
                else:
                    receiver["audio"] += 1
                    count = frame.samples * (1 if frame.format.is_planar else len(frame.layout.channels))
                    data = memoryview(frame.planes[0])[:count * frame.format.bytes]
                    if frame.format.name in ("s16", "s16p"):
                        receiver["nonzeroAudioFrames"] += any(abs(sample) > 64 for sample in data.cast("h"))
                    elif frame.format.name in ("flt", "fltp"):
                        receiver["nonzeroAudioFrames"] += any(abs(sample) > .005 for sample in data.cast("f"))
        except (asyncio.CancelledError, Exception):
            pass

    @pc.on("track")
    def received(track):
        consumers.append(asyncio.create_task(consume(track)))

    async def wait_color(pressed):
        before = receiver["frames"]
        async with asyncio.timeout(20):
            while True:
                if signal_task and signal_task.done():
                    await signal_task
                    raise AssertionError("Selkies signalling ended before playback")
                rgb = receiver["rgb"]
                if rgb and receiver["frames"] > before:
                    matches = (rgb[0] < 90 if pressed else rgb[0] > 170) if system == "gb" else (rgb[0] > rgb[1] + 30 if pressed else rgb[1] > rgb[0] + 30)
                    if matches:
                        return list(rgb)
                await asyncio.sleep(.01)

    async def hold(buttons):
        nonlocal sequence
        while True:
            sequence += 1
            await inputs.send_json({"sequence": sequence, "buttons": buttons, "inputEpoch": epoch})
            await asyncio.sleep(.1)

    try:
        await other.api(f"/api/games/{rom['id']}/native-sessions", "POST", {"clientId": secrets.token_hex(16), "ticket": secrets.token_hex(32), "streamingBackend": backend}, expected=409)
        if backend == "selkies":
            prefix = urlparse(launch["url"]).path.rstrip("/")
            for asset in ["", "home-viewer.js", "src/selkies-core.js"]:
                async with home.client.get(home.base + prefix + "/" + asset) as response:
                    assert response.status == 200 and len(await response.read()) > 100, (asset, response.status)
                async with other.client.get(home.base + prefix + "/" + asset) as response:
                    assert response.status in (401, 404, 410), (asset, response.status)
            for asset in ("api/tokens", "api/files/", "api/screenshot", "api/switch"):
                async with home.client.get(home.base + prefix + "/" + asset) as response:
                    assert response.status == 404, (asset, response.status)
            async with home.client.get(home.base + prefix + "/api/turn") as response:
                assert response.status == 200 and (await response.json())["iceServers"] == []
            async with home.client.request("OPTIONS", home.base + f"/game-native/{launch['id']}/whep", headers={"Authorization": "Bearer " + ticket}) as response:
                assert response.status == 410
            signal, signal_task = await connect_selkies(home, launch, ticket, pc)
        else:
            for kind, wanted in [("video", "video/h264"), ("audio", "audio/opus")]:
                tx = pc.addTransceiver(kind, direction="recvonly")
                tx.setCodecPreferences([codec for codec in RTCRtpReceiver.getCapabilities(kind).codecs if codec.mimeType.lower() == wanted])
            await pc.setLocalDescription(await pc.createOffer())
            async with home.client.post(home.base + launch["url"], data=pc.localDescription.sdp, headers={"Authorization": "Bearer " + ticket, "Content-Type": "application/sdp"}) as response:
                assert response.status == 201, await response.text()
                answer = await response.text()
                answer = "\r\n".join(line for line in answer.splitlines() if not line.startswith("a=candidate:") or " " + home.media_host + " 62405 " in line) + "\r\n"
                await pc.setRemoteDescription(RTCSessionDescription(type="answer", sdp=answer))
        inputs = await home.client.ws_connect(home.base + f"/api/games/native/sessions/{launch['id']}/input-stream", origin=home.base)
        await inputs.send_json({"ticket": ticket})
        assert (await inputs.receive(timeout=3)).data == "ok"
        epoch = (await command("resume"))["inputEpoch"]
        pulse = asyncio.create_task(hold(0))
        colors = [await wait_color(False)]
        # Only these original programs drive their console's sound hardware.
        # Selkies suppresses silent PCM; silent fixtures need an Opus track,
        # not manufactured audio packets. Tone fixtures must decode real sound.
        if tone_fixture:
            async with asyncio.timeout(8):
                while receiver["nonzeroAudioFrames"] == 0:
                    await asyncio.sleep(.05)
        samples = []
        for buttons in [1 << 8, 0, 1 << 8, 0]:
            pulse.cancel()
            await asyncio.gather(pulse, return_exceptions=True)
            started = time.monotonic()
            pulse = asyncio.create_task(hold(buttons))
            colors.append(await wait_color(bool(buttons)))
            samples.append(round((time.monotonic() - started) * 1000, 1))
        assert pc.connectionState == "connected" and any(tx.kind == "audio" for tx in pc.getTransceivers()), receiver
        assert not tone_fixture or receiver["nonzeroAudioFrames"] > 0, receiver
        pulse.cancel()
        await asyncio.gather(pulse, return_exceptions=True)
        pulse = None
        await inputs.close()
        inputs = None
        saved = await command("save")
        assert saved["hasSave"]
        frame = gba_frame(container) if system == "gba" else None
        await home.api(f"/api/games/native/sessions/{launch['id']}/input", "POST", {"sequence": sequence + 1, "buttons": 1 << 8, "inputEpoch": epoch}, expected=409)
        await command("end")
        active = False
        assert not any(processes(container).values()), processes(container)
        assert not await home.api("/api/games/sessions/active")
        return {"backend": backend, "version": launch["version"], "running": running, "idleAfter": processes(container),
                "receiver": dict(receiver), "audioFixture": "tone" if tone_fixture else "silence", "opusNegotiated": True, "observedInputColors": colors, "savedFrame": frame, "diagnosticToDecodedFrameMs": samples,
                "saveRestored": bool(expected_version), "exactGbaFrameRestored": expected_frame is not None,
                "sameSessionRetry": True, "foreignLoginDenied": True, "backendChangeRequiresNewSession": True}
    except Exception as error:
        raise RuntimeError(f"{system}/{backend}: {error!r}; receiver={receiver}; peer={pc.connectionState}") from error
    finally:
        if pulse:
            pulse.cancel()
            await asyncio.gather(pulse, return_exceptions=True)
        if inputs:
            await inputs.close()
        if signal:
            await signal.close()
        if signal_task:
            signal_task.cancel()
            await asyncio.gather(signal_task, return_exceptions=True)
        await pc.close()
        for consumer in consumers:
            consumer.cancel()
        await asyncio.gather(*consumers, return_exceptions=True)
        if active:
            try:
                await command("discard")
            except Exception:
                pass


async def main(args):
    assert ipaddress.ip_address(urlparse(args.base).hostname).is_private
    assert docker("inspect", args.container, "--format", '{{index .Config.Labels "home.isolated-verification"}}') == "selkies"
    assert docker("exec", args.container, "id", "-u") == "1654"
    fixtures = Path(args.fixtures)
    assert "ORIGINAL SYNTHETIC" in (fixtures / "README.txt").read_text()
    home, other = Home(args.base), Home(args.base)
    home.media_host = args.media_host or urlparse(args.base).hostname
    report = {"originalIsolatedFixturesOnly": True, "browserAutomation": False, "internetMediaRequests": 0, "cases": [], "errors": []}
    try:
        info = await home.session()
        if info["configured"]:
            assert args.continue_isolated or args.resume, "Existing installation preserved"
            await home.login()
        else:
            await home.api("/api/setup", "POST", {"displayName": lan.NAME, "password": lan.PASSWORD})
            await home.session()
        assert not await home.api("/api/games/sessions/active")
        if args.resume:
            previous = json.loads(Path(args.resume).read_text())
            assert previous["originalIsolatedFixturesOnly"] and not previous["errors"]
            for case in previous["cases"]:
                entry = await home.api("/api/games/" + case["gameId"])
                assert entry["romSha256"] == case["romSha256"] and entry["state"]["favorite"] and entry["state"]["hasSave"]
            if previous.get("shutdownGame"):
                entry = await home.api("/api/games/" + previous["shutdownGame"]["id"])
                assert entry["state"]["saveRevision"] > previous["shutdownGame"]["saveRevision"]
                report["activeShutdownCheckpointPreserved"] = True
            assert not any(processes(args.container).values())
            report["recreationPreserved"] = True
        else:
            await other.login()
            preferences = (await home.api("/api/games/library/settings"))["options"]
            await home.api("/api/games/library/settings", "PUT", preferences | {"automaticMetadata": False})
            status = await home.api("/api/games/native/backends")
            assert status["defaultBackend"] == "standard" and all(item["available"] for item in status["items"]), status
            report["idleBefore"] = processes(args.container)
            assert not any(report["idleBefore"].values())
            report["installedKiB"] = docker("exec", args.container, "du", "-sk", "/app/SelkiesRuntime", "/opt/selkies")
            for system in args.systems.split(","):
                assert system in lan.SYSTEMS
                try:
                    rom = await import_fixture(home, system, fixtures)
                    case = {"system": system, "gameId": rom["id"], "romSha256": rom["sha256"], "runs": []}
                    report["cases"].append(case)
                    first = await play(home, other, rom, system, "standard", args.container)
                    case["runs"].append(first)
                    Path(args.output).write_text(json.dumps(report, indent=2))
                    second = await play(home, other, rom, system, "selkies", args.container, first["version"], first["savedFrame"])
                    case["runs"].append(second)
                    Path(args.output).write_text(json.dumps(report, indent=2))
                    final = await play(home, other, rom, system, "standard", args.container, first["version"], second["savedFrame"])
                    case["runs"].append(final)
                    print(json.dumps(case), flush=True)
                except Exception as error:
                    report["errors"].append({"system": system, "error": repr(error)})
                    print(json.dumps(report["errors"][-1]), flush=True)
                    break
                Path(args.output).write_text(json.dumps(report, indent=2))
            if args.leave_active and not report["errors"]:
                case = next(item for item in report["cases"] if item["system"] == "gba")
                entry = await home.api("/api/games/" + case["gameId"])
                launch = await home.api(f"/api/games/{case['gameId']}/native-sessions", "POST", {"clientId": secrets.token_hex(16), "ticket": secrets.token_hex(32), "streamingBackend": "selkies"})
                await home.api(f"/api/games/native/sessions/{launch['id']}/command", "POST", {"action": "resume"})
                report["shutdownGame"] = {"id": case["gameId"], "saveRevision": entry["state"]["saveRevision"]}
        assert not await home.api("/api/downloads")
        Path(args.output).write_text(json.dumps(report, indent=2))
        assert not report["errors"], report["errors"]
    finally:
        await home.client.close()
        await other.client.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", required=True)
    parser.add_argument("--fixtures", required=True)
    parser.add_argument("--container", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--systems", default=",".join(lan.SYSTEMS))
    parser.add_argument("--continue-isolated", action="store_true")
    parser.add_argument("--media-host")
    parser.add_argument("--leave-active", action="store_true")
    parser.add_argument("--resume")
    asyncio.run(main(parser.parse_args()))
